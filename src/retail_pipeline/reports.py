def money(v) -> str:
    return "-" if pd.isna(v) else f"${v:,.0f}"


def pct(v) -> str:
    return "-" if pd.isna(v) else f"{v:+.1f}%"


def table_html(df: pd.DataFrame) -> str:
    if df.empty:
        return "<p><i>No rows.</i></p>"
    head = "".join(f"<th>{html.escape(str(c))}</th>" for c in df.columns)
    body = "".join(
        "<tr>" + "".join(f"<td>{html.escape(str(v))}</td>" for v in row) + "</tr>" for row in df.itertuples(index=False)
    )
    return f"<table><tr>{head}</tr>{body}</table>"


def bars_html(df: pd.DataFrame, label: str, value: str) -> str:
    if df.empty:
        return ""
    top = float(df[value].max()) or 1.0
    rows = "".join(
        f"<tr><td>{html.escape(str(r[label]))}</td><td style='width:60%'><div class='bar' style='width:{float(r[value]) / top * 100:.0f}%'></div></td>"
        f"<td>{money(r[value])}</td></tr>"
        for _, r in df.iterrows()
    )
    return f"<table>{rows}</table>"


def render_page(title: str, subtitle: str, kpis: list[tuple[str, str]], sections: list[tuple[str, str]]) -> str:
    cards = "".join(f"<div class='kpi'><b>{html.escape(v)}</b><span>{html.escape(k)}</span></div>" for k, v in kpis)
    body = "".join(f"<h2>{html.escape(h)}</h2>{content}" for h, content in sections)
    return (f"<!doctype html><html><head><meta charset='utf-8'><title>{html.escape(title)}</title><style>{CSS}</style></head>"
            f"<body><h1>{html.escape(title)}</h1><p class='sub'>{html.escape(subtitle)}</p><div class='kpis'>{cards}</div>{body}</body></html>")


def _q(engine: Engine, sql: str, **params) -> pd.DataFrame:
    with engine.connect() as c:
        return pd.read_sql(text(sql), c, params=params)


def daily_report(engine: Engine, report_date: date, out_dir: Path) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    rev = _q(engine, "select * from marts.rpt_daily_revenue where order_date <= :d order by order_date desc limit 14", d=report_date)
    if rev.empty:
        raise RuntimeError("marts.rpt_daily_revenue has no data - did dbt run?")
    today = rev.iloc[0]
    actual = today["order_date"]
    kpis = [
        ("Net revenue", money(today["net_revenue"])),
        ("Orders", f"{int(today['orders']):,}"),
        ("Avg order value", money(today["avg_order_value"])),
        ("vs same day last week", pct(today["net_revenue_wow_pct"])),
    ]
    top = _q(engine,
             """select p.product_name as product, p.category, sum(f.quantity) as units, round(sum(f.net_amount), 0) as net_revenue
                from marts.fact_order_items f join marts.dim_product p on p.product_key = f.product_key
                where f.order_date = :d and f.is_revenue_order group by 1, 2 order by 4 desc limit 5""", d=actual)
    inv = _q(engine, "select product_name, category, stock_on_hand, reorder_level, days_of_cover, stock_status "
                     "from marts.rpt_inventory_status where stock_status <> 'healthy' order by days_of_cover nulls first limit 10")
    mkt = _q(engine, "select channel, round(spend, 0) as spend, orders, round(net_revenue, 0) as net_revenue, round(roas, 2) as roas "
                     "from marts.rpt_marketing_performance where report_date = :d order by net_revenue desc", d=actual)
    health = _q(engine, "select table_name, rows_extracted, rows_valid, rows_quarantined, duplicates_removed, status "
                        "from audit.ingestion_batches where logical_date = :d order by table_name", d=actual)
    trend = rev.sort_values("order_date")[["order_date", "net_revenue"]]
    note = "" if actual == report_date else f" (latest available data; requested {report_date})"
    page = render_page(
        f"Daily revenue report - {actual}", f"Generated by retail-data-platform{note}", kpis,
        [("Net revenue, last 14 days", bars_html(trend, "order_date", "net_revenue")),
         ("Top products", table_html(top)), ("Marketing by channel", table_html(mkt)),
         ("Inventory needing attention", table_html(inv)), ("Pipeline health for the day", table_html(health))],
    )
    path = out_dir / f"daily_revenue_{actual}.html"
    path.write_text(page, encoding="utf-8")
    rev.sort_values("order_date").to_csv(out_dir / f"daily_revenue_{actual}.csv", index=False)
    return path


def weekly_report(engine: Engine, end_date: date, out_dir: Path) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    start = end_date - timedelta(days=6)
    cur = _q(engine, "select * from marts.rpt_daily_revenue where order_date between :a and :b order by order_date", a=start, b=end_date)
    prev = _q(engine, "select sum(net_revenue) as net, sum(orders) as orders from marts.rpt_daily_revenue where order_date between :a and :b",
              a=start - timedelta(days=7), b=start - timedelta(days=1))
    if cur.empty:
        raise RuntimeError("no revenue data for the requested week")
    net, orders = float(cur["net_revenue"].sum()), int(cur["orders"].sum())
    prev_net = prev.iloc[0]["net"]
    growth = (net / float(prev_net) - 1) * 100 if pd.notna(prev_net) and float(prev_net) else float("nan")
    cats = _q(engine, """select p.category, round(sum(f.net_amount), 0) as net_revenue, round(sum(f.gross_margin), 0) as gross_margin
                         from marts.fact_order_items f join marts.dim_product p on p.product_key = f.product_key
                         where f.order_date between :a and :b and f.is_revenue_order group by 1 order by 2 desc""", a=start, b=end_date)
    chan = _q(engine, """select channel, round(sum(spend), 0) as spend, round(sum(net_revenue), 0) as net_revenue,
                         round(sum(net_revenue) / nullif(sum(spend), 0), 2) as roas from marts.rpt_marketing_performance
                         where report_date between :a and :b group by 1 order by 3 desc""", a=start, b=end_date)
    page = render_page(
        f"Weekly summary - {start} to {end_date}", "Generated by retail-data-platform",
        [("Net revenue", money(net)), ("Orders", f"{orders:,}"), ("Avg order value", money(net / orders if orders else float('nan'))), ("vs previous week", pct(growth))],
        [("Daily net revenue", bars_html(cur[["order_date", "net_revenue"]], "order_date", "net_revenue")),
         ("Category performance", table_html(cats)), ("Channel efficiency", table_html(chan))],
    )
    path = out_dir / f"weekly_summary_{end_date}.html"
    path.write_text(page, encoding="utf-8")
    return path
